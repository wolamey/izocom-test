// Функция для получения новости по slug
// В будущем: export const fetchNewsBySlug = async (slug: string): Promise<NewsArticle | null> => { ... }
export const getNewsBySlug = (slug: string): NewsArticle | undefined => {
  return newsArticles.find(article => article.slug === slug);
};

// Функция для получения новости по id
export const getNewsById = (id: string): NewsArticle | undefined => {
  return newsArticles.find(article => article.id === id);
};

// Функция для получения соседних новостей (предыдущая/следующая)
export const getAdjacentNews = (currentSlug: string): { prev?: NewsArticle; next?: NewsArticle } => {
  const currentIndex = newsArticles.findIndex(article => article.slug === currentSlug);
  if (currentIndex === -1) return {};
  
  return {
    prev: currentIndex < newsArticles.length - 1 ? newsArticles[currentIndex + 1] : undefined,
    next: currentIndex > 0 ? newsArticles[currentIndex - 1] : undefined,
  };
};

// Функция для получения похожих новостей
export const getRelatedNews = (currentSlug: string, limit: number = 3): NewsArticle[] => {
  return newsArticles
    .filter(article => article.slug !== currentSlug)
    .slice(0, limit);
};
